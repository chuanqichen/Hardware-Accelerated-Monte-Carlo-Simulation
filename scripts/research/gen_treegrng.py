"""Generate TreeGRNG variants at wider output widths with the authors' generator.

Wraps rtl/third_party/treegrng/makeVerilogCode.py (vendored, unmodified) to produce
RESULTLENGTH-bit designs so the comparison with our Q3.12 table is at matched output
width (prototype plan step 1 / claim T1). Two patches applied at import time only:
scipy's norm.pdf is replaced by statistics.NormalDist (no scipy here), and the LFSR
seeds are made deterministic. The generator writes real-valued threshold parameters,
which VCS accepts but Design Compiler does not, so an `_int.sv` copy with the
truncated integer thresholds is emitted alongside, same as for the 8-bit example.

    python3 scripts/research/gen_treegrng.py --bits 12 --lsb-per-sigma 512
    python3 scripts/research/gen_treegrng.py --bits 16 --lsb-per-sigma 8192
Writes rtl/third_party/treegrng/gen/treegrng<bits>.sv and treegrng<bits>_int.sv
(top module RandDist, ports clk, LD_seed, result[bits-1:0]).
"""
from __future__ import annotations

import argparse
import random
import re
import sys
import types
from pathlib import Path
from statistics import NormalDist

ROOT = Path(__file__).resolve().parents[2]
TG = ROOT / "rtl" / "third_party" / "treegrng"


def load_generator():
    # scipy shim
    shim = types.ModuleType("scipy.stats")
    shim.norm = types.SimpleNamespace(pdf=lambda x: NormalDist().pdf(x))
    sys.modules["scipy"] = types.ModuleType("scipy"); sys.modules["scipy.stats"] = shim
    src = (TG / "makeVerilogCode.py").read_text()
    # strip the module-level call at the end so we can call printVerilog ourselves
    src = re.sub(r"\nprintVerilog\(getTresholds\(WEIGHTS.*$", "\n", src, flags=re.S)
    ns = {}
    exec(compile(src, "makeVerilogCode.py", "exec"), ns)
    return ns


def integerize(sv: str, bits: int, acc: int) -> str:
    """Replace .T(<real>*(2**(BITNUMS<+-d>)-1)) with the truncated integer, as Verilog does."""
    def repl(m):
        frac = float(m.group(1)); d = m.group(2) or ""
        L = acc + (int(d) if d else 0)
        T = int(frac * ((1 << L) - 1))
        return f".T({L}'d{T})"
    out = re.sub(r"\.T\(([\d.]+)\*\(2\*\*\(BITNUMS([+-]\d+)?\)-1\)\)", repl, sv)
    assert not re.search(r"\.T\([\d.]+\*", out), "real-valued threshold left behind"
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bits", type=int, required=True, help="RESULTLENGTH (output width)")
    ap.add_argument("--lsb-per-sigma", type=int, required=True, help="output scale, e.g. 32 for the 8-bit example")
    ap.add_argument("--internal-acc", type=int, default=None, help="threshold/LFSR width (default = bits)")
    ap.add_argument("--seed", type=int, default=382)
    ap.add_argument("--lfsr-amount", type=int, default=4, help="distinct LFSR lengths (authors: 4, max 8)")
    ap.add_argument("--tag", default="", help="suffix for the output file name")
    a = ap.parse_args()
    acc = a.internal_acc or a.bits
    random.seed(a.seed)
    g = load_generator()
    n = 1 << a.bits
    half = n // 2
    weights = [NormalDist().pdf((x - half) / a.lsb_per_sigma) for x in range(n)]
    out_dir = TG / "gen"; out_dir.mkdir(exist_ok=True)
    path = out_dir / f"treegrng{a.bits}{a.tag}.sv"
    g["printVerilog"](g["getTresholds"](weights, a.bits), str(path), a.bits, acc, a.lfsr_amount, True, True, True)
    sv = path.read_text()
    hdr = (f"// GENERATED by scripts/research/gen_treegrng.py from the TreeGRNG authors' makeVerilogCode.py\n"
           f"// RESULTLENGTH={a.bits} INTERNAL_ACC={acc} LSB/sigma={a.lsb_per_sigma} seed={a.seed}. Top: RandDist.\n")
    path.write_text(hdr + sv)
    (out_dir / f"treegrng{a.bits}{a.tag}_int.sv").write_text(hdr.replace("Top: RandDist", "Top: RandDist_int, integer thresholds for DC")
                                                      + integerize(sv, a.bits, acc).replace("module RandDist", "module RandDist_int"))
    print(f"wrote {path} and {path.with_name(path.stem + '_int.sv')}  ({len(sv.splitlines())} lines)")


if __name__ == "__main__":
    main()
