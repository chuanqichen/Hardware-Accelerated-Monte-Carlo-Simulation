"""Giles & Sheridan-Methven piecewise-linear dyadic approximation of Phi^-1 in hardware form (R4).

Their Theorem 2.5 construction: intervals geometrically decaying toward the tail with rate
r = 1/2, a per-interval L2-optimal linear fit, index taken from the float exponent. Hardware
transcription with the same front end as gauss_lut_seg (31-bit tail-side magnitude m, band
k = clz31(m)), but instead of 2^B stored cells per band it stores one (intercept, slope) pair
and multiplies by the F fraction bits below the leading one:

    mag = alpha_k - beta_k * f,   f = F bits of m below the leading one, in [0, 1)

alpha_k is Q3.12 (16 b), beta_k is UQ1.14 scaled per band (16 b), f is UQ0.F; the product is
rounded half-to-even and the result saturated to Q3.12 (shared round_sat policy). Output is
exact and enumerable: per band 2^F distinct f values of equal probability.

    python3 model/gauss_lut_pwl.py                        # sweep K, F -> FoM table
    python3 model/gauss_lut_pwl.py --export DIR --segments 12 --frac-bits 12
"""
from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path
from statistics import NormalDist

import numpy as np

from fxp import Fxp

ROOT = Path(__file__).resolve().parents[1]
N = NormalDist()
Z_FMT = Fxp(16, 12)


@dataclass(frozen=True)
class PwlConfig:
    segments: int = 12     # K bands (last absorbs the tail)
    frac_bits: int = 12    # F: fraction bits multiplied by the slope
    beta_frac: int = 14    # slope stored as UQ1.14 (|beta| < 2 for all bands)

    @property
    def name(self):
        return f"pwl_K{self.segments}_F{self.frac_bits}"


class PwlLut:
    def __init__(self, cfg: PwlConfig, n_quad: int = 4096):
        self.cfg = cfg; K = cfg.segments
        self.alpha = np.zeros(K, dtype=np.int64); self.beta = np.zeros(K, dtype=np.int64)
        bfmt = Fxp(cfg.beta_frac + 2, cfg.beta_frac)          # room for sign in quantize; stored unsigned
        for k in range(K):
            lo, hi = (2.0 ** -(k + 2), 2.0 ** -(k + 1)) if k < K - 1 else (0.0, 2.0 ** -(k + 1))
            f = (np.arange(n_quad) + 0.5) / n_quad                 # midpoints in the band
            t = lo + f * (hi - lo)
            g = np.array([N.inv_cdf(1.0 - ti) for ti in t])        # magnitude, decreasing in f
            # L2-optimal line g ~ a + b f  (normal equations on the midpoint sample)
            A = np.vstack([np.ones_like(f), f]).T
            a, b = np.linalg.lstsq(A, g, rcond=None)[0]
            self.alpha[k] = Z_FMT.quantize(a, saturate=True)
            self.beta[k] = int(round(-b * (1 << cfg.beta_frac)))  # store |slope| (slope is negative)
            assert 0 <= self.beta[k] < (1 << (cfg.beta_frac + 2)), (k, b)

    def _mag(self, k, f_int):
        """Bit-exact: alpha - round_half_even(beta * f / 2^F) in Q3.12, saturated."""
        cfg = self.cfg
        prod = self.beta[k] * f_int                                 # UQ1.(beta_frac+F)
        sh = cfg.beta_frac + cfg.frac_bits - Z_FMT.frac
        half = 1 << (sh - 1)
        q = (prod + half) >> sh
        q = np.where((prod & ((1 << sh) - 1)) == half, (prod >> sh) + ((prod >> sh) & 1), q)   # ties to even
        mag = self.alpha[k] - q
        return np.clip(mag, 0, Z_FMT.max_raw)

    def lookup(self, u):
        u = np.asarray(u, dtype=np.uint64); K, F = self.cfg.segments, self.cfg.frac_bits
        sign = (u >> np.uint64(31)) & np.uint64(1)
        m = np.where(sign == 1, (~u) & np.uint64(0x7FFFFFFF), u & np.uint64(0x7FFFFFFF)).astype(np.int64)
        msb = np.where(m > 0, np.floor(np.log2(np.maximum(m, 1))).astype(np.int64), -1)
        k = np.clip(30 - msb, 0, K - 1)
        shift = 30 - k - F
        f = np.where(shift >= 0, (m >> np.maximum(shift, 0)) & ((1 << F) - 1), (m << np.maximum(-shift, 0)) & ((1 << F) - 1))
        mag = self._mag(k, f)
        return np.where(sign == 1, mag, -mag)

    def distribution(self):
        K, F = self.cfg.segments, self.cfg.frac_bits
        zs, ps = [], []
        for k in range(K):
            width = (2.0 ** -(k + 2) if k < K - 1 else 2.0 ** -(k + 1)) / (1 << F)
            f = np.arange(1 << F)
            mag = Z_FMT.to_real(self._mag(k, f))
            zs += [mag, -mag]; ps += [np.full(len(f), width)] * 2
        return np.concatenate(zs), np.concatenate(ps)


def write_rom_sv(lut: PwlLut, path: Path):
    cfg = lut.cfg; kb = max(1, int(np.ceil(np.log2(cfg.segments))))
    L = [f"// Generated by model/gauss_lut_pwl.py - {cfg.name}. alpha Q3.12, beta UQ1.{cfg.beta_frac} (|slope| per band).",
         f"module gauss_lut_pwl_rom #(parameter int K_BITS = {kb}) (input logic [K_BITS-1:0] k, output logic [15:0] alpha, output logic [15:0] beta);",
         "  always_comb begin", "    case (k)"]
    for i in range(cfg.segments):
        L.append(f"      {kb}'d{i}: begin alpha = 16'h{int(lut.alpha[i]) & 0xFFFF:04x}; beta = 16'h{int(lut.beta[i]) & 0xFFFF:04x}; end")
    L += ["      default: begin alpha = '0; beta = '0; end", "    endcase", "  end", "endmodule", ""]
    path.write_text("\n".join(L))


def main():
    import grng_fom
    ap = argparse.ArgumentParser(); ap.add_argument("--export", type=Path); ap.add_argument("--segments", type=int, default=12)
    ap.add_argument("--frac-bits", type=int, default=12); a = ap.parse_args()
    if a.export:
        cfg = PwlConfig(a.segments, a.frac_bits); lut = PwlLut(cfg); a.export.mkdir(parents=True, exist_ok=True)
        write_rom_sv(lut, a.export / "gauss_lut_pwl_rom.sv")
        rng = np.random.default_rng(382); u = np.concatenate([[0, 0xFFFFFFFF, 0x7FFFFFFF, 0x80000000, 1, 0x7FFFFFFE], rng.integers(0, 1 << 32, 10000)]).astype(np.uint64)
        z = lut.lookup(u); vec = ROOT / "tb/vectors" / f"gauss_lut_pwl_K{a.segments}_F{a.frac_bits}.hex"
        vec.write_text("".join(f"{int(ui):08x} {Z_FMT.to_hex(zi)}\n" for ui, zi in zip(u, z)))
        print(f"wrote {a.export} and {vec} ({len(u)} vectors)"); return
    print(f"{'table':<14}{'coef bits':>10}{'max|z|':>7}{'KS':>8}{'P>3.5 err%':>11}{'call worst':>11}{'dig K200':>9}")
    for K in (8, 12, 16):
        for F in (8, 12):
            lut = PwlLut(PwlConfig(K, F)); z, p = lut.distribution(); r = grng_fom.fom(z, p, lut.cfg.name)
            print(f"{lut.cfg.name:<14}{K*32:>10}{np.abs(z).max():>7.2f}{r['ks']:>8.4f}{r['tail_3.5_rel_err_pct']:>+11.1f}{r['call_worst_bias_pct']:>10.3f}%{r['digital_K200_bias_pct']:>+8.1f}%")


if __name__ == "__main__":
    main()
